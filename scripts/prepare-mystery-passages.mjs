import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Source: the official eng-web-c_vpl.txt (see SCRIPTURE-LICENSE.txt).
const source = await readFile(process.argv[2], 'utf8');
const selections = {
  joyful: ['LUK 1:26-38', 'LUK 1:39-45', 'LUK 2:1-7', 'LUK 2:22-32', 'LUK 2:41-52'],
  luminous: ['MAT 3:13-17', 'JOH 2:1-11', 'MAR 1:14-15', 'LUK 9:28-36', 'LUK 22:14-20'],
  sorrowful: ['MAT 26:36-46', 'JOH 19:1', 'MAT 27:27-31', 'LUK 23:26-32', 'JOH 19:25-30'],
  glorious: ['MAT 28:1-10', 'LUK 24:50-53', 'ACT 2:1-4', 'LUK 1:46-49', 'REV 12:1'],
};
const names = { LUK: 'Luke', MAT: 'Matthew', JOH: 'John', MAR: 'Mark', ACT: 'Acts', REV: 'Revelation' };
const verses = new Map();
for (const line of source.split(/\r?\n/)) {
  const match = /^([A-Z0-9]{3} \d+:\d+) (.+)$/.exec(line);
  if (match) verses.set(match[1], match[2].trim());
}
const passages = {};
for (const [set, refs] of Object.entries(selections)) {
  passages[set] = refs.map(ref => {
    const [book, chapter, first, last = first] = ref.split(/[ :-]/);
    const text = [];
    for (let v = +first; v <= +last; v++) {
      const key = `${book} ${chapter}:${v}`;
      if (!verses.get(key)) throw new Error(`Missing Scripture: ${key}`);
      text.push(verses.get(key));
    }
    return { reference: `${names[book]} ${chapter}:${first}${last === first ? '' : `–${last}`}`, text: text.join(' ') };
  });
}
await writeFile(new URL('../src/mystery-passages.js', import.meta.url),
  `// Generated by scripts/prepare-mystery-passages.mjs from WEB Catholic Edition, SHA-256 ${createHash('sha256').update(source).digest('hex')}.\nexport const PASSAGES = ${JSON.stringify(passages, null, 2)};\n`);
