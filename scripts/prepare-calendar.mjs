import { readFile, writeFile } from 'node:fs/promises';
import { Romcal } from 'romcal';
import { UnitedStates_En } from '@romcal/calendar.united-states';

const startYear = 2024;
const endYear = 2035;
const readPackage = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const engine = await readPackage('../node_modules/romcal/package.json');
const calendar = await readPackage('../node_modules/@romcal/calendar.united-states/package.json');
if (engine.version !== calendar.version) throw new Error('Use matching pinned romcal engine and calendar versions.');
const options = { localizedCalendar: UnitedStates_En, scope: 'gregorian', epiphanyOnSunday: true, corpusChristiOnSunday: true };
const sunday = new Romcal({ ...options, ascensionOnSunday: true });
const thursday = new Romcal({ ...options, ascensionOnSunday: false });
const days = {};
const thursdayOverrides = {};
function normalize(events, date) {
  if (!events?.length || events.some(event => event.date !== date || !event.name?.trim())) {
    throw new Error(`Missing or unlocalized calendar data for ${date}.`);
  }
  const primary = events[0];
  const day = {
    season: primary.seasons.at(-1),
    week: primary.calendar.weekOfSeason,
    celebrations: events.map(event => ({
      id: event.id, name: event.name, rank: event.rank,
      colors: event.id === 'commemoration_of_all_the_faithful_departed'
        ? [...new Set([...event.colors, 'WHITE'])] : event.colors,
      optional: event.isOptional,
    })),
  };
  // GNLY 15 permits the BVM memorial on unimpeded Saturdays of Ordinary Time.
  if (day.season === 'ORDINARY_TIME' && primary.rank === 'WEEKDAY'
    && new Date(`${date}T12:00:00Z`).getUTCDay() === 6) {
    day.celebrations.push({
      id: 'blessed_virgin_mary_on_saturday', name: 'Blessed Virgin Mary on Saturday',
      rank: 'OPTIONAL_MEMORIAL', colors: ['WHITE'], optional: true,
    });
  }
  return day;
}
for (let year = startYear; year <= endYear; year++) {
  const main = await sunday.generateCalendar(year);
  const alternate = await thursday.generateCalendar(year);
  const count = year % 4 === 0 ? 366 : 365;
  if (Object.keys(main).length !== count || Object.keys(alternate).length !== count) {
    throw new Error(`Incomplete civil calendar for ${year}.`);
  }
  for (const date of Object.keys(main).sort()) {
    days[date] = normalize(main[date], date);
    const other = normalize(alternate[date], date);
    if (JSON.stringify(days[date]) !== JSON.stringify(other)) thursdayOverrides[date] = other;
  }
}
const metadata = { startYear, endYear, generator: 'romcal', version: engine.version, calendar: 'UnitedStates_En' };
await writeFile(new URL('../src/liturgical-data.js', import.meta.url),
  `// Generated by scripts/prepare-calendar.mjs. See CALENDAR-LICENSE.txt.\nexport const CALENDAR_SOURCE = ${JSON.stringify(metadata)};\nexport const LITURGICAL_DAYS = ${JSON.stringify(days)};\nexport const THURSDAY_OVERRIDES = ${JSON.stringify(thursdayOverrides)};\n`);
console.log(`Prepared ${Object.keys(days).length} U.S. calendar days, ${startYear}-${endYear}; ${Object.keys(thursdayOverrides).length} Ascension-variant days.`);
